import type { ISODate } from './types'

/**
 * The Top 100 course registry.
 *
 * This is the single source of truth for course data, as `drills.ts` is for drills and `clubs.ts`
 * is for the club vocabulary. Nothing here is restated in markup.
 *
 * The ranking is Golf Australia's Top 100 Australian Courses for 2026, linked once as
 * `RANKING_SOURCE` rather than repeated on every entry — all 100 come from the one article.
 *
 * **Every `summary` is original prose written for this site.** The ranking article's per-course
 * text is panel commentary by named judges, and it is deliberately not reproduced in any form:
 * `dist/` is publicly readable on a real domain. Rank, name, location and architect are facts and
 * are stored as such. Club logos are used at 64px to identify the club they belong to — nominative
 * use, the ordinary purpose of a favicon.
 *
 * **`access` and `greenFee` are a dated snapshot, not a live feed (D37).** `checkedOn` records
 * when each was looked at. They are refreshed by hand, never automatically, and a fee that had
 * moved on is a stale figure rather than a wrong one.
 *
 * Two rules govern what is absent. A club whose access could not be confirmed against its own site
 * is `'unknown'` — never `'members'`, which would be inventing a finding. A fee that could not be
 * confirmed is absent entirely, never `0`: an absent fee renders as a dash, and a `0` renders as
 * free.
 */

export type CourseSlug = string

export type AusState = 'NSW' | 'VIC' | 'QLD' | 'SA' | 'WA' | 'TAS' | 'NT' | 'ACT'

/**
 * How a non-member gets on. `'limited'` is the sandbelt norm — visitor times exist but are
 * conditional. `'unknown'` is a real answer, and the one that must never be rounded to
 * `'members'`.
 */
export type Access = 'public' | 'limited' | 'members' | 'unknown'

/** Absent, never `0`. An unpublished fee is a dash, not a free round. */
export interface GreenFee {
  amount: number
  currency: 'AUD'
  /** What the amount actually covers — which round, which day, which season. */
  note?: string
}

export interface Course {
  slug: CourseSlug
  /** 1-100, the 2026 Golf Australia ranking. Each rank appears exactly once. */
  rank: number
  name: string
  suburb: string
  state: AusState
  lat: number
  lon: number
  /** With dates where the ranking gives them. */
  architects: string[]
  /** Written for this site. Never the published panel commentary. */
  summary: string
  /** The club's own site. */
  site?: string
  /** The visitor-rates page specifically, where one exists. */
  visitorUrl?: string
  access: Access
  /** What the club publishes. Where `access` is `'unknown'` this says what is believed and that
   *  it is unverified — it never asserts a policy the research could not confirm. */
  accessNote?: string
  greenFee?: GreenFee
  /** `'logos/<slug>.png'`, relative to the site root. Present only where the file exists. */
  logo?: string
  /** When access, fee and site were looked at. */
  checkedOn?: ISODate
}

